/**
 * Quiz generation via the Anthropic Messages API. Provider/model are plain
 * config (env vars), not hardcoded, so swapping models or rotating the key
 * never requires touching this file.
 */

const QUIZ_TOOL = {
  name: 'submit_quiz',
  description: 'Submit the generated weekly quiz in the exact structured format required by the site.',
  input_schema: {
    type: 'object',
    properties: {
      subtitle: {
        type: 'string',
        description: 'Short subtitle naming this week\'s topic, in Spanish, e.g. "Semana del 24 de marzo · Diálisis peritoneal".',
      },
      questions: {
        type: 'array',
        minItems: 3,
        maxItems: 3,
        items: {
          type: 'object',
          properties: {
            question: { type: 'string' },
            option_a: { type: 'string' },
            option_b: { type: 'string' },
            option_c: { type: 'string' },
            option_d: { type: 'string' },
            correct_index: { type: 'integer', minimum: 0, maximum: 3 },
            explanation: { type: 'string' },
          },
          required: ['question', 'option_a', 'option_b', 'option_c', 'option_d', 'correct_index', 'explanation'],
        },
      },
    },
    required: ['subtitle', 'questions'],
  },
};

function buildPrompt({ avoidTopics, changeComment }) {
  let prompt = `Genera un quiz semanal de salud renal para el sitio web Raíces Médicas, dirigido al público general de Latinoamérica (NO para profesionales de la salud).

Requisitos:
- Exactamente 3 preguntas de opción múltiple (4 opciones cada una, una sola correcta).
- Español claro, sencillo y cercano, sin tecnicismos innecesarios. Si usas un término médico, explícalo en la misma pregunta o explicación.
- Cada explicación debe ser breve (1-3 oraciones) y precisa médicamente.
- Elige un tema de salud renal específico para la semana (prevención, diálisis, trasplante, nutrición renal, enfermedad renal crónica, hipertensión y riñón, diabetes y riñón, hidratación, síntomas de alerta, etc.) y escribe un subtítulo que lo refleje.`;

  if (avoidTopics && avoidTopics.length > 0) {
    prompt += `\n\nTemas ya usados en semanas recientes — NO los repitas, elige un ángulo distinto:\n${avoidTopics.map((t) => `- ${t}`).join('\n')}`;
  }

  if (changeComment) {
    prompt += `\n\nEl revisor pidió este ajuste sobre la versión anterior del borrador: "${changeComment}"\nAplica ese cambio y genera una versión nueva y completa (no un parche).`;
  }

  prompt += '\n\nUsa la herramienta submit_quiz para entregar el resultado.';
  return prompt;
}

/**
 * Returns { subtitle, questions } as generated by the model, or throws.
 * Does not validate business rules (correct_index range, etc.) — the
 * caller (validate.js) must do that; it relies on the API's tool schema
 * doing the bulk of the format enforcement.
 */
export async function generateQuiz(env, { avoidTopics = [], changeComment = null } = {}) {
  const res = await fetch(`${env.ANTHROPIC_API_BASE}/v1/messages`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': env.QUIZ_ANTHROPIC_API_KEY,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({
      model: env.ANTHROPIC_MODEL,
      max_tokens: 2048,
      tools: [QUIZ_TOOL],
      tool_choice: { type: 'tool', name: 'submit_quiz' },
      messages: [{ role: 'user', content: buildPrompt({ avoidTopics, changeComment }) }],
    }),
  });

  if (!res.ok) {
    const body = await res.text();
    throw new Error(`Anthropic API error ${res.status}: ${body.slice(0, 500)}`);
  }

  const data = await res.json();
  const toolUse = (data.content || []).find((block) => block.type === 'tool_use' && block.name === 'submit_quiz');
  if (!toolUse) {
    throw new Error('Anthropic response did not include a submit_quiz tool call');
  }
  return toolUse.input;
}
